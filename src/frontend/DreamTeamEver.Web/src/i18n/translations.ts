export type TranslationMessages = typeof translations.en

type NestedKeyOf<T, Prefix extends string = ''> = T extends string
  ? Prefix extends '' ? never : Prefix
  : T extends Record<string, unknown>
    ? {
        [K in keyof T & string]: NestedKeyOf<T[K], Prefix extends '' ? K : `${Prefix}.${K}`>
      }[keyof T & string]
    : never

export type TranslationKey = NestedKeyOf<TranslationMessages>

function getNestedValue(obj: Record<string, unknown>, path: string): string | undefined {
  const parts = path.split('.')
  let current: unknown = obj
  for (const part of parts) {
    if (current === null || typeof current !== 'object' || !(part in current)) return undefined
    current = (current as Record<string, unknown>)[part]
  }
  return typeof current === 'string' ? current : undefined
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const primary = getNestedValue(translations[locale] as Record<string, unknown>, key)
  const fallback = getNestedValue(translations.en as Record<string, unknown>, key)
  let text = primary ?? fallback ?? key

  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{{${name}}}`, String(value))
    }
  }

  return text
}
